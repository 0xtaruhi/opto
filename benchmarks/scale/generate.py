"""Emit the deterministic tiered scale corpus described by `scale.toml`.

The corpus exists to measure RFC 0013 Phase 3 scheduling behaviour, so it is
generated rather than fetched. A generated corpus is the only way to reach a
chosen post-sealing operation count exactly, to cover every class named by the
`Regional scale contract` in `../README.md`, and to stay redistributable.

Two properties matter more than realism and are therefore checked rather than
assumed:

* Determinism. The same tier always emits byte-identical SystemVerilog, so
  `scale.toml` can pin a SHA-256 per file and the harness can prove that a
  measurement used the intended input.
* Non-trivial parallelism. Tiles are heterogeneous and consume their
  neighbours through a ring plus a shared broadcast bus. Replicating one core
  N times would expose perfect, embarrassingly parallel work and would inflate
  every speedup and utilization number the phase gate reads.

Source text stays small because the shape is carried by `generate` loops: the
elaborated operation count grows with the tier parameters while the emitted
bytes stay in the tens of kilobytes.
"""

import argparse
import hashlib
import sys
from pathlib import Path


HEADER = (
    "// SPDX-FileCopyrightText: 2026 Zhengyi Zhang\n"
    "// SPDX-License-Identifier: GPL-3.0-only\n"
    "//\n"
    "// Generated by benchmarks/scale/generate.py. Do not edit.\n"
    "// Regenerate with: benchmarks/scale/generate.py --tier {tier} OUTPUT_DIR\n"
)


# Tier parameters are calibrated against measured `normalized_operations`, not
# derived from a closed-form estimate: normalization folds constants and shares
# common subexpressions, so the elaborated count is not a function of the source
# alone. `scale.toml` records the measured count each tier produces.
TIERS = {
    "small": {
        "tiles": 320,
        "width": 64,
        "lanes": 32,
        "stages": 24,
        "memory_depth": 256,
        "fanout_sinks": 64,
        "control_arms": 128,
    },
    "medium": {
        "tiles": 3072,
        "width": 64,
        "lanes": 64,
        "stages": 48,
        "memory_depth": 1024,
        "fanout_sinks": 128,
        "control_arms": 256,
    },
    "large": {
        "tiles": 24576,
        "width": 64,
        "lanes": 96,
        "stages": 64,
        "memory_depth": 4096,
        "fanout_sinks": 192,
        "control_arms": 256,
    },
}

# Tile classes are assigned round-robin over the ring so that neighbouring tiles
# have different cost and different critical structure. A uniform ring would let
# the scheduler settle into a single steady state and would not exercise the
# ready-queue depth the phase gate measures.
TILE_CLASSES = (
    "arith",
    "control",
    "fanout",
    "pipeline",
    "memory",
    "cdc",
)


def package_source(tier, parameters):
    """Emit shared parameters so every tile agrees on the interconnect shape."""
    return f"""{HEADER.format(tier=tier)}
package scale_pkg;

  parameter int unsigned TILES = {parameters["tiles"]};
  parameter int unsigned WIDTH = {parameters["width"]};
  parameter int unsigned LANES = {parameters["lanes"]};
  parameter int unsigned STAGES = {parameters["stages"]};
  parameter int unsigned MEMORY_DEPTH = {parameters["memory_depth"]};
  parameter int unsigned FANOUT_SINKS = {parameters["fanout_sinks"]};
  parameter int unsigned ADDRESS_WIDTH = $clog2(MEMORY_DEPTH);

  typedef struct packed {{
    logic [WIDTH-1:0] data;
    logic [7:0]       tag;
    logic             valid;
  }} beat_t;

endpackage
"""


def arith_tile_source(tier):
    """Wide multiply-accumulate lanes: arithmetic-dense, deep logic per lane."""
    return f"""{HEADER.format(tier=tier)}
module scale_arith_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  localparam logic [7:0] TILE_TAG = TILE_ID % 256;

  logic [WIDTH-1:0] lane_result [LANES];

  for (genvar lane = 0; lane < int'(LANES); lane++) begin : g_lane
    // Typed localparams rather than inline casts: a genvar is a signed int, so
    // casting it inline mixes signedness into every use.
    localparam logic [WIDTH-1:0] LANE_OFFSET = lane + TILE_ID;
    localparam logic [WIDTH-1:0] LANE_STRIDE = lane * 7 + 1;

    logic [WIDTH-1:0] operand_a;
    logic [WIDTH-1:0] operand_b;
    logic [WIDTH-1:0] accumulator;

    assign operand_a = upstream.data ^ LANE_OFFSET;
    assign operand_b = broadcast.data + LANE_STRIDE;

    always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
        accumulator <= '0;
      end else if (upstream.valid) begin
        // Truncating multiply keeps the lane width fixed while still forcing a
        // full-width partial-product network through mapping.
        accumulator <= accumulator + (operand_a * operand_b);
      end
    end

    assign lane_result[lane] = accumulator;
  end

  // A reduction tree across lanes couples the lanes together, so the tile is
  // not a bundle of independent narrow slices.
  logic [WIDTH-1:0] reduced;
  always_comb begin
    reduced = '0;
    for (int unsigned lane = 0; lane < LANES; lane++) begin
      reduced = reduced ^ lane_result[lane];
    end
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      downstream <= '{{data: '0, tag: '0, valid: 1'b0}};
    end else begin
      downstream.data  <= reduced;
      downstream.tag   <= upstream.tag + TILE_TAG;
      downstream.valid <= upstream.valid;
    end
  end

endmodule
"""


def control_tile_source(tier):
    """Control-dense: a wide case decode feeding an FSM with sparse encoding."""
    return f"""{HEADER.format(tier=tier)}
module scale_control_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  localparam logic [7:0] TILE_TAG = TILE_ID % 256;

  typedef enum logic [2:0] {{
    S_IDLE,
    S_DECODE,
    S_ISSUE,
    S_WAIT,
    S_RETIRE,
    S_FAULT
  }} state_e;

  state_e state;
  state_e next_state;

  logic [WIDTH-1:0] decoded;
  logic [7:0]       opcode;

  assign opcode = upstream.tag ^ broadcast.tag;

  // A dense case over the opcode space: control logic that does not reduce to
  // a datapath operator, which is what makes this tile expensive to map.
  always_comb begin
    decoded = '0;
    case (opcode)
      default: decoded = upstream.data;
"""


def control_tile_cases(parameters):
    """Emit the opcode case arms that make the control tile decode-dominated.

    Every arm must be a distinct expression. An earlier revision repeated the
    same eight expressions across all sixty-four opcodes; normalization shared
    the common subexpressions and collapsed the decode back down to eight
    cones, which defeated the point of the tile.
    """
    arms = []
    arm_count = parameters["control_arms"]
    width = parameters["width"]
    selector_width = max(8, (arm_count - 1).bit_length())
    for index in range(arm_count):
        selector = f"{selector_width}'d{index}"
        # The per-arm constant is what keeps the arms distinct under common
        # subexpression sharing. It is emitted as a sized unsigned literal
        # because an unsized decimal literal is signed, which would mix
        # signedness into every arm.
        constant = f"{width}'d{index * 2654435761 % 65521}"
        shift = index % (16 if index % 16 else 15) + 1
        expression = {
            0: f"(upstream.data + broadcast.data) ^ {constant}",
            1: f"(upstream.data - broadcast.data) + {constant}",
            2: f"(upstream.data & broadcast.data) | {constant}",
            3: f"(upstream.data | broadcast.data) ^ {constant}",
            4: f"(upstream.data ^ broadcast.data) - {constant}",
            5: f"{{upstream.data[WIDTH-1-{shift}:0], {shift}'b0}} ^ {constant}",
            6: f"{{{shift}'b0, upstream.data[WIDTH-1:{shift}]}} + {constant}",
            7: f"(~upstream.data) ^ {constant}",
        }[index % 8]
        arms.append(f"      {selector}: decoded = {expression};")
    return "\n".join(arms)


def fanout_tile_source(tier):
    """High-fanout: one driver observed by many independent sinks."""
    return f"""{HEADER.format(tier=tier)}
module scale_fanout_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  localparam logic [7:0] TILE_TAG = TILE_ID % 256;

  // A single high-fanout control net. Fanout tree synthesis and residual
  // cloning are the phases this tile is meant to stress.
  logic select;
  assign select = ^(upstream.data ^ broadcast.data);

  logic [WIDTH-1:0] sink_value [FANOUT_SINKS];

  for (genvar sink = 0; sink < int'(FANOUT_SINKS); sink++) begin : g_sink
    localparam logic [WIDTH-1:0] SINK_BIAS = sink;

    logic [WIDTH-1:0] captured;

    always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
        captured <= '0;
      end else if (select) begin
        captured <= upstream.data + SINK_BIAS;
      end else begin
        captured <= broadcast.data ^ SINK_BIAS;
      end
    end

    assign sink_value[sink] = captured;
  end

  logic [WIDTH-1:0] merged;
  always_comb begin
    merged = '0;
    for (int unsigned sink = 0; sink < FANOUT_SINKS; sink++) begin
      merged = merged + sink_value[sink];
    end
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      downstream <= '{{data: '0, tag: '0, valid: 1'b0}};
    end else begin
      downstream.data  <= merged;
      downstream.tag   <= upstream.tag + TILE_TAG;
      downstream.valid <= upstream.valid;
    end
  end

endmodule
"""


def pipeline_tile_source(tier):
    """Deep pipeline: a long register chain with real work between stages."""
    return f"""{HEADER.format(tier=tier)}
module scale_pipeline_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  beat_t stage [STAGES+1];

  assign stage[0] = upstream;

  for (genvar depth = 0; depth < int'(STAGES); depth++) begin : g_stage
    // Per-stage logic differs by depth so retiming cannot collapse the chain
    // into a shift register.
    localparam logic [WIDTH-1:0] STAGE_BIAS = depth + TILE_ID;

    logic [WIDTH-1:0] transformed;

    always_comb begin
      case (depth % 4)
        0: transformed = stage[depth].data + broadcast.data;
        1: transformed = stage[depth].data ^ {{stage[depth].data[0], stage[depth].data[WIDTH-1:1]}};
        2: transformed = stage[depth].data - STAGE_BIAS;
        default: transformed = stage[depth].data & ~broadcast.data;
      endcase
    end

    always_ff @(posedge clk or negedge rst_n) begin
      if (!rst_n) begin
        stage[depth+1] <= '{{data: '0, tag: '0, valid: 1'b0}};
      end else begin
        stage[depth+1].data  <= transformed;
        stage[depth+1].tag   <= stage[depth].tag;
        stage[depth+1].valid <= stage[depth].valid;
      end
    end
  end

  assign downstream = stage[STAGES];

endmodule
"""


def memory_tile_source(tier):
    """Memory: an inferred synchronous-read register file with write priority."""
    return f"""{HEADER.format(tier=tier)}
module scale_memory_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  localparam logic [7:0] TILE_TAG = TILE_ID % 256;

  localparam logic [ADDRESS_WIDTH-1:0] TILE_ADDRESS = TILE_ID % MEMORY_DEPTH;

  logic [WIDTH-1:0] storage [MEMORY_DEPTH];

  logic [ADDRESS_WIDTH-1:0] write_address;
  logic [ADDRESS_WIDTH-1:0] read_address;
  logic                     write_enable;

  assign write_address = upstream.data[ADDRESS_WIDTH-1:0];
  assign read_address  = broadcast.data[ADDRESS_WIDTH-1:0] ^ TILE_ADDRESS;
  assign write_enable  = upstream.valid & ~broadcast.valid;

  logic [WIDTH-1:0] read_data;

  always_ff @(posedge clk) begin
    if (write_enable) begin
      storage[write_address] <= upstream.data ^ broadcast.data;
    end
    read_data <= storage[read_address];
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      downstream <= '{{data: '0, tag: '0, valid: 1'b0}};
    end else begin
      downstream.data  <= read_data;
      downstream.tag   <= upstream.tag + TILE_TAG;
      downstream.valid <= upstream.valid;
    end
  end

endmodule
"""


def cdc_tile_source(tier):
    """Multi-clock: a second domain joined by explicit two-flop synchronizers."""
    return f"""{HEADER.format(tier=tier)}
module scale_cdc_tile
  import scale_pkg::*;
#(
  parameter int unsigned TILE_ID = 0
) (
  input  logic  clk,
  input  logic  secondary_clk,
  input  logic  rst_n,
  input  beat_t upstream,
  input  beat_t broadcast,
  output beat_t downstream
);

  localparam logic [7:0] TILE_TAG = TILE_ID % 256;

  // Launch domain.
  logic [WIDTH-1:0] launch_data;
  logic             launch_toggle;

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      launch_data   <= '0;
      launch_toggle <= 1'b0;
    end else if (upstream.valid) begin
      launch_data   <= upstream.data + broadcast.data;
      launch_toggle <= ~launch_toggle;
    end
  end

  // Capture domain: two-flop synchronizer on the toggle, data held stable.
  logic toggle_meta;
  logic toggle_sync;
  logic toggle_delayed;

  always_ff @(posedge secondary_clk or negedge rst_n) begin
    if (!rst_n) begin
      toggle_meta    <= 1'b0;
      toggle_sync    <= 1'b0;
      toggle_delayed <= 1'b0;
    end else begin
      toggle_meta    <= launch_toggle;
      toggle_sync    <= toggle_meta;
      toggle_delayed <= toggle_sync;
    end
  end

  logic capture_enable;
  assign capture_enable = toggle_sync ^ toggle_delayed;

  logic [WIDTH-1:0] captured;
  always_ff @(posedge secondary_clk or negedge rst_n) begin
    if (!rst_n) begin
      captured <= '0;
    end else if (capture_enable) begin
      captured <= launch_data;
    end
  end

  always_ff @(posedge secondary_clk or negedge rst_n) begin
    if (!rst_n) begin
      downstream <= '{{data: '0, tag: '0, valid: 1'b0}};
    end else begin
      downstream.data  <= captured;
      downstream.tag   <= upstream.tag + TILE_TAG;
      downstream.valid <= capture_enable;
    end
  end

endmodule
"""


def top_source(tier, parameters):
    """Wire the tiles into a ring plus a broadcast bus.

    The ring is what makes the corpus a scheduling problem rather than a batch
    of independent designs: tile N consumes tile N-1, so the work graph has real
    depth, while the broadcast bus gives every tile a shared reader.

    Tiles are instantiated from a `generate` loop rather than emitted one block
    at a time. The medium tier needs thousands of instances to reach its
    operation target, and emitting those textually would produce a
    multi-megabyte top file for no benefit; the loop keeps the source at a size
    a reviewer can actually read.
    """
    branches = []
    for offset, tile_class in enumerate(TILE_CLASSES):
        secondary = (
            "        .secondary_clk(secondary_clk),\n" if tile_class == "cdc" else ""
        )
        keyword = "if" if offset == 0 else "end else if"
        branches.append(
            f"""      {keyword} (tile % {len(TILE_CLASSES)} == {offset}) begin : g_{tile_class}
        scale_{tile_class}_tile #(
          .TILE_ID(tile)
        ) u_tile (
          .clk(clk),
{secondary}          .rst_n(rst_n),
          .upstream(ring[(tile + int'(TILES) - 1) % int'(TILES)]),
          .broadcast(broadcast),
          .downstream(ring[tile])
        );"""
        )
    body = "\n".join(branches) + "\n      end"
    return f"""{HEADER.format(tier=tier)}
module scale_top
  import scale_pkg::*;
(
  input  logic              clk,
  input  logic              secondary_clk,
  input  logic              rst_n,
  input  logic [WIDTH-1:0]  inject_data,
  input  logic [7:0]        inject_tag,
  input  logic              inject_valid,
  output logic [WIDTH-1:0]  collect_data,
  output logic [7:0]        collect_tag,
  output logic              collect_valid
);

  beat_t ring [TILES];
  beat_t broadcast;

  // The broadcast beat is derived from the ring tail, so the bus is a real
  // shared dependency rather than a free-running input.
  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      broadcast <= '{{data: '0, tag: '0, valid: 1'b0}};
    end else begin
      broadcast.data  <= ring[TILES-1].data ^ inject_data;
      broadcast.tag   <= ring[TILES-1].tag ^ inject_tag;
      broadcast.valid <= ring[TILES-1].valid | inject_valid;
    end
  end

  for (genvar tile = 0; tile < int'(TILES); tile++) begin : g_tile
{body}
  end

  assign collect_data  = ring[TILES-1].data;
  assign collect_tag   = ring[TILES-1].tag;
  assign collect_valid = ring[TILES-1].valid;

endmodule
"""


def build_sources(tier, parameters):
    """Return the ordered {filename: text} map for one tier."""
    control = control_tile_source(tier) + control_tile_cases(parameters) + """
    endcase
  end

  always_comb begin
    case (state)
      S_IDLE:   next_state = upstream.valid ? S_DECODE : S_IDLE;
      S_DECODE: next_state = S_ISSUE;
      S_ISSUE:  next_state = broadcast.valid ? S_WAIT : S_RETIRE;
      S_WAIT:   next_state = upstream.valid ? S_RETIRE : S_WAIT;
      S_RETIRE: next_state = S_IDLE;
      S_FAULT:  next_state = S_IDLE;
      default:  next_state = S_FAULT;
    endcase
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= S_IDLE;
    end else begin
      state <= next_state;
    end
  end

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      downstream <= '{data: '0, tag: '0, valid: 1'b0};
    end else begin
      downstream.data  <= decoded;
      downstream.tag   <= upstream.tag + TILE_TAG;
      downstream.valid <= (state == S_RETIRE);
    end
  end

endmodule
"""
    # Order is fixed and not sorted by name: the package must precede the tiles
    # that import it, and the top must come last.
    return {
        "scale_pkg.sv": package_source(tier, parameters),
        "scale_arith_tile.sv": arith_tile_source(tier),
        "scale_control_tile.sv": control,
        "scale_fanout_tile.sv": fanout_tile_source(tier),
        "scale_pipeline_tile.sv": pipeline_tile_source(tier),
        "scale_memory_tile.sv": memory_tile_source(tier),
        "scale_cdc_tile.sv": cdc_tile_source(tier),
        "scale_top.sv": top_source(tier, parameters),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--tier",
        required=True,
        choices=sorted(TIERS),
        help="corpus tier to emit",
    )
    parser.add_argument(
        "output",
        type=Path,
        help="directory to write the generated SystemVerilog into",
    )
    parser.add_argument(
        "--print-hashes",
        action="store_true",
        help="print the SHA-256 of each emitted file for scale.toml",
    )
    arguments = parser.parse_args(argv)

    parameters = TIERS[arguments.tier]
    sources = build_sources(arguments.tier, parameters)

    arguments.output.mkdir(parents=True, exist_ok=True)
    for name, text in sources.items():
        # Written as bytes with an explicit newline policy so the hash does not
        # depend on the host's text-mode translation.
        (arguments.output / name).write_bytes(text.encode("utf-8"))

    if arguments.print_hashes:
        for name, text in sources.items():
            digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
            print(f'{digest}  {name}')

    return 0


if __name__ == "__main__":
    sys.exit(main())
